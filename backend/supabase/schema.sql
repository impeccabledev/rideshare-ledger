create extension if not exists pgcrypto;

create table if not exists public.groups (
  id text primary key,
  join_code_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  member_id text primary key,
  group_id text not null references public.groups(id) on delete cascade,
  name text not null,
  phone text,
  active boolean not null default true,
  one_way_total numeric(10,2) not null default 0,
  two_way_total numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  unique (group_id, phone)
);

create table if not exists public.entries (
  entry_id text primary key,
  group_id text not null references public.groups(id) on delete cascade,
  date date not null,
  driver_id text not null,
  day_type text not null check (day_type in ('one_way', 'two_way')),
  day_total_used numeric(10,2) not null,
  total_amount numeric(10,2) not null default 0,
  notes text not null default '',
  created_at timestamptz not null default now(),
  unique (group_id, date)
);

create table if not exists public.entry_riders (
  id bigint generated by default as identity primary key,
  entry_id text not null references public.entries(entry_id) on delete cascade,
  group_id text not null references public.groups(id) on delete cascade,
  member_id text not null,
  trip_type text not null check (trip_type in ('one_way', 'two_way')),
  units integer not null,
  charge numeric(10,2) not null,
  unique (entry_id, member_id)
);

create index if not exists idx_members_group on public.members(group_id);
create index if not exists idx_entries_group_date on public.entries(group_id, date desc);
create index if not exists idx_entry_riders_entry on public.entry_riders(entry_id);
create index if not exists idx_entry_riders_group on public.entry_riders(group_id);

alter table public.groups enable row level security;
alter table public.members enable row level security;
alter table public.entries enable row level security;
alter table public.entry_riders enable row level security;

-- Explicit grants ensure the backend service role can access all tables.
-- RLS is still enabled, but the service role bypasses row-level policies.
grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;

-- The backend uses the Supabase service-role key and bypasses RLS.

create or replace function public.create_group(p_group_id text, p_join_code text)
returns void
language sql
security invoker
as $$
  insert into public.groups (id, join_code_hash)
  values (lower(trim(p_group_id)), crypt(trim(p_join_code), gen_salt('bf', 12)))
  on conflict (id) do update
  set join_code_hash = excluded.join_code_hash;
$$;

create or replace function public.verify_group(p_group_id text, p_join_code text)
returns boolean
language sql
security invoker
as $$
  select exists (
    select 1
    from public.groups
    where id = lower(trim(p_group_id))
      and join_code_hash = crypt(trim(p_join_code), join_code_hash)
  );
$$;

grant execute on function public.create_group(text, text) to service_role;
grant execute on function public.verify_group(text, text) to service_role;
